/**
 * JAVASCRIPT SET THEORY NOTES
 * 
 * 1. What is a Set?
 * - Set is an ES6 built-in data structure used to store a collection of UNIQUE values.
 * - Duplicate values are automatically ignored and rejected.
 * 
 * 2. Key Characteristics:
 * - Value Uniqueness: Every value can occur only ONCE in a Set.
 * - Any Data Type: Can store Primitives or Object references.
 * - Insertion Order: Retains insertion order during iteration.
 * - Size Property: Has a direct .size property for O(1) count lookup.
 * 
 * 3. Primary Set Methods:
 * - set.add(value)      -> Adds a new unique value.
 * - set.has(value)      -> Returns true if value exists in Set, else false.
 * - set.delete(value)   -> Removes value from Set.
 * - set.clear()         -> Removes all elements from Set.
 */
